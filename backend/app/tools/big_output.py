"""大输出演示工具：返回远超上下文阈值的大文本，用于演示「大文件落盘」能力。

输出固定在 5000+ 字符（默认落盘阈值 context_offload_threshold=3000），
调用一次即可在工具结果层触发 maybe_offload：正文写盘、上下文只留指针，
前端出现「大输出落盘」卡片。仅用于能力演示，不产生任何副作用。
"""
from langchain_core.tools import tool

# 单段演示文本模板（约 180 字符），重复拼接出超阈值的大输出
_LINE = (
    "「大输出落盘」能力演示：这是工具输出正文。企业级上下文管理会在源头把超大单条输出"
    "写盘并只留指针，避免挤占窗口。本段用于凑足阈值长度——当工具输出超过 "
    "context_offload_threshold 时，后续内容会被移动到 data/offload 目录，"
    "上下文保留可回读的指针。"
)


@tool
def big_output(topic: str = "") -> str:
    """生成一段超大文本（5000+ 字符）用于演示「大文件落盘」：输出正文会超出上下文阈值，
    被自动写盘并替换为短指针，触发落盘卡片展示。

    Args:
        topic: 可选主题词，插入演示文本开头；留空使用默认演示文案。
    """
    head = f"【{topic}】" if topic else ""
    # 拼接 28 段（约 5000+ 字符），稳定超默认 3000 字符的落盘阈值
    body = "\n".join(_LINE for _ in range(28))
    return f"{head}大输出演示文档（大文件落盘演示）\n{body}\n—— 演示结束 ——"
